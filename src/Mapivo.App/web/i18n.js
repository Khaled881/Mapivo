let currentLang = 'en';

function T(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let s = dict[key] != null ? dict[key] : (I18N.en[key] != null ? I18N.en[key] : key);
  if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
}

function translateDom(root) {
  (root || document).querySelectorAll('[data-i18n],[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18n;
    const val = T(key);
    if (val !== key) el.textContent = val;
    const titleKey = el.dataset.i18nTitle;
    if (titleKey) { const tv = T(titleKey); if (tv !== titleKey) el.title = tv; }
  });
}

function getMapivoLang() { return currentLang; }

function setMapivoLang(lang) {
  if (lang !== 'fa' && lang !== 'en') lang = 'en';
  const changed = lang !== currentLang;
  currentLang = lang;
  const root = document.getElementById('htmlRoot') || document.documentElement;
  root.setAttribute('lang', lang);
  root.setAttribute('dir', lang === 'fa' ? 'rtl' : 'ltr');
  document.body.classList.toggle('rtl', lang === 'fa');
  translateDom(document);
  try { localStorage.setItem('mapivo.lang', lang); } catch { }
  const sel = document.getElementById('setLanguage');
  if (sel && sel.value !== lang) sel.value = lang;
  if (changed) document.dispatchEvent(new CustomEvent('pf-lang', { detail: lang }));
  return lang;
}

try {
  const saved = localStorage.getItem('mapivo.lang');
  if (saved === 'fa' || saved === 'en') currentLang = saved;
} catch { }

document.addEventListener('DOMContentLoaded', () => {
  const root = document.getElementById('htmlRoot') || document.documentElement;
  root.setAttribute('lang', currentLang);
  root.setAttribute('dir', currentLang === 'fa' ? 'rtl' : 'ltr');
  if (currentLang === 'fa') document.body.classList.add('rtl');
  translateDom(document);
});

window.T = T;
window.setMapivoLang = setMapivoLang;
window.getMapivoLang = getMapivoLang;
